import { OutcomeTag, ResultTag, StateValue } from '../components/common';
import { StateDiagram } from '../components/StateDiagram';
import { TimelineGrid, timelineSummary } from '../components/PipelineView';
import { parseSequence } from '../core/parser';
import { buildTimeline } from '../core/pipeline';
import { simulate } from '../core/simulator';

const SECTIONS = [
  ['branches', 'Branches and control hazards'],
  ['pipeline', 'The pipeline'],
  ['prediction', 'Why predict?'],
  ['one-bit', '1-bit predictor'],
  ['two-bit', '2-bit saturating counter'],
  ['worked', 'Worked example'],
  ['metrics', 'Accuracy, cycles and CPI'],
  ['limits', 'Limitations and real predictors'],
] as const;

/** Worked example produced by the simulator itself, so the page can never disagree with it. */
const WORKED_SEQUENCE = 'T T N T';
const workedEvents = (() => {
  const r = parseSequence(WORKED_SEQUENCE);
  if (!r.ok) throw new Error('worked example must parse');
  return r.events;
})();
const workedOne = simulate('one-bit', 0, workedEvents);
const workedTwo = simulate('two-bit', 1, workedEvents);

function timeline(mispredicted: boolean) {
  const r = buildTimeline({ depth: 5, penalty: 2, mispredicted, predictedTaken: true });
  if (!r.ok) throw new Error(r.reason);
  return r.timeline;
}
const correctTimeline = timeline(false);
const mispredictTimeline = timeline(true);

export function LearnPage() {
  return (
    <div className="doc-layout">
      <nav className="doc-toc" aria-label="On this page">
        <p className="doc-toc__title">On this page</p>
        <ol>
          {SECTIONS.map(([id, title]) => (
            <li key={id}>
              <a href={`#${id}`} onClick={(e) => { e.preventDefault(); document.getElementById(id)?.scrollIntoView({ behavior: 'smooth', block: 'start' }); }}>
                {title}
              </a>
            </li>
          ))}
        </ol>
      </nav>

      <article className="doc">
        <h1>Branch prediction: the concepts</h1>
        <p className="lead">
          A short reference for the ideas behind the simulator. Every table of predictor behaviour on this page is generated by the same code that runs the simulator.
        </p>

        <section id="branches">
          <h2>1. Branches and control hazards</h2>
          <p>
            A <strong>branch instruction</strong> chooses the address of the next instruction. A conditional branch such as{' '}
            <code>beq x1, x2, loop</code> either jumps to its <em>target</em> (TAKEN) or continues with the next sequential instruction, the{' '}
            <em>fall-through</em> (NOT TAKEN).
          </p>
          <p>
            In a pipeline, the processor must fetch the next instruction every cycle, but the branch's condition and target are only known a few stages later.
            Not knowing what to fetch is a <strong>control hazard</strong>. Waiting (stalling) until the branch resolves wastes those cycles on every branch.
          </p>
        </section>

        <section id="pipeline">
          <h2>2. A simple five-stage pipeline</h2>
          <table className="data-table doc-table">
            <thead>
              <tr>
                <th scope="col">Stage</th>
                <th scope="col">Work done</th>
              </tr>
            </thead>
            <tbody>
              <tr><th scope="row" className="mono">IF</th><td>Instruction Fetch: read the instruction at the PC; choose the next PC.</td></tr>
              <tr><th scope="row" className="mono">ID</th><td>Instruction Decode: decode, read registers.</td></tr>
              <tr><th scope="row" className="mono">EX</th><td>Execute: ALU operation; in this model, branches compare and resolve here.</td></tr>
              <tr><th scope="row" className="mono">MEM</th><td>Memory Access: loads and stores.</td></tr>
              <tr><th scope="row" className="mono">WB</th><td>Write Back: write the result to the register file.</td></tr>
            </tbody>
          </table>
          <p>
            Ideally, one instruction enters each cycle and one completes each cycle once the pipeline is full, so I instructions take I + (L − 1) cycles on an
            L-stage pipeline. The diagrams below assume the branch resolves in EX, two cycles after fetch, so P = 2. Real designs resolve branches in different stages
            and have different penalties.
          </p>

          <h3>Correct prediction</h3>
          <TimelineGrid timeline={correctTimeline} caption="Branch predicted TAKEN, actually TAKEN (P = 2, L = 5)" />
          <p className="pipeline-summary">{timelineSummary(correctTimeline)}</p>

          <h3>Misprediction</h3>
          <TimelineGrid timeline={mispredictTimeline} caption="Branch predicted TAKEN, actually NOT TAKEN (P = 2, L = 5)" />
          <p className="pipeline-summary">{timelineSummary(mispredictTimeline)}</p>
        </section>

        <section id="prediction">
          <h2>3. Why predict?</h2>
          <p>
            Instead of stalling, the processor <strong>guesses</strong> the branch direction in IF and keeps fetching along the guessed path (speculation).
          </p>
          <ul>
            <li><strong>Correct prediction:</strong> the speculatively fetched instructions are the right ones. No cycles are lost.</li>
            <li>
              <strong>Misprediction:</strong> the wrong-path instructions are <em>flushed</em> (turned into bubbles) before they change any architectural state, and
              fetch restarts at the correct address. The cycles spent on wrong-path work are the <strong>misprediction penalty</strong>.
            </li>
          </ul>
          <p>Because most branches behave in a repetitive way (loops, rarely-taken error checks), remembering recent behaviour gives good guesses.</p>
        </section>

        <section id="one-bit">
          <h2>4. The 1-bit predictor</h2>
          <p>
            Keep one bit per branch address: <span className="mono">1</span> = predict TAKEN, <span className="mono">0</span> = predict NOT TAKEN. After the branch
            resolves, set the bit to the actual outcome. In other words: <em>predict that the branch does what it did last time</em>.
          </p>
          <StateDiagram kind="one-bit" current={null} lastTransition={null} />
          <p>
            A single unusual outcome flips the prediction immediately. For a loop branch, the exit (N) flips the bit, so the first iteration of the next execution of
            the loop is also mispredicted: <strong>two mispredictions per loop visit</strong>.
          </p>
        </section>

        <section id="two-bit">
          <h2>5. The 2-bit saturating counter</h2>
          <table className="data-table doc-table">
            <thead>
              <tr>
                <th scope="col">Counter</th>
                <th scope="col">State</th>
                <th scope="col">Prediction</th>
              </tr>
            </thead>
            <tbody>
              {([0, 1, 2, 3] as const).map((s) => (
                <tr key={s}>
                  <td className="mono">{s.toString(2).padStart(2, '0')}</td>
                  <td>{['Strongly Not Taken', 'Weakly Not Taken', 'Weakly Taken', 'Strongly Taken'][s]}</td>
                  <td>{s >= 2 ? 'TAKEN' : 'NOT TAKEN'}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <StateDiagram kind="two-bit" current={null} lastTransition={null} />
          <ul>
            <li>The prediction is read from the <strong>old</strong> counter value, before the branch resolves.</li>
            <li>Actual TAKEN: counter + 1, but never above <span className="mono">11</span>. Actual NOT TAKEN: counter − 1, but never below <span className="mono">00</span>.</li>
            <li>From a strong state, it takes <strong>two</strong> consecutive wrong outcomes to change the prediction.</li>
          </ul>
          <p>
            This hysteresis is why a 2-bit counter usually tolerates an occasional anomalous outcome, such as a loop exit, better than a 1-bit predictor: one surprise
            only weakens the state. It is not guaranteed to be better. For some patterns (for example <span className="mono">T T N N T T N N</span> from{' '}
            <span className="mono">01</span>, against a 1-bit predictor starting at <span className="mono">0</span>) the counter changes its mind too slowly and makes more
            mispredictions than the 1-bit predictor.
          </p>
        </section>

        <section id="worked">
          <h2>6. Worked example</h2>
          <p>
            Sequence <span className="mono">{WORKED_SEQUENCE}</span> for a single branch. 1-bit starts at <span className="mono">0</span>; 2-bit starts at{' '}
            <span className="mono">01</span>.
          </p>
          <div className="table-scroll">
            <table className="data-table doc-table">
              <thead>
                <tr>
                  <th scope="col" rowSpan={2} className="num">Step</th>
                  <th scope="col" rowSpan={2}>Actual</th>
                  <th scope="colgroup" colSpan={3} className="group">1-bit</th>
                  <th scope="colgroup" colSpan={3} className="group">2-bit</th>
                </tr>
                <tr>
                  <th scope="col" className="group-start">Bit before</th>
                  <th scope="col">Prediction</th>
                  <th scope="col">Bit after</th>
                  <th scope="col" className="group-start">Counter before</th>
                  <th scope="col">Prediction</th>
                  <th scope="col">Counter after</th>
                </tr>
              </thead>
              <tbody>
                {workedOne.trace.map((a, i) => {
                  const b = workedTwo.trace[i];
                  return (
                    <tr key={a.step}>
                      <td className="num mono">{a.step}</td>
                      <td><OutcomeTag outcome={a.actual} /></td>
                      <td className="group-start"><StateValue kind="one-bit" state={a.stateBefore} showName={false} /></td>
                      <td><OutcomeTag outcome={a.predicted} /> <ResultTag correct={a.correct} /></td>
                      <td><StateValue kind="one-bit" state={a.stateAfter} showName={false} /></td>
                      <td className="group-start"><StateValue kind="two-bit" state={b.stateBefore} /></td>
                      <td><OutcomeTag outcome={b.predicted} /> <ResultTag correct={b.correct} /></td>
                      <td><StateValue kind="two-bit" state={b.stateAfter} /></td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
          <p>
            Result: 1-bit {workedOne.trace.length - workedOne.mispredictions} correct, {workedOne.mispredictions} mispredicted; 2-bit{' '}
            {workedTwo.trace.length - workedTwo.mispredictions} correct, {workedTwo.mispredictions} mispredicted. At step 3 the single N flips the 1-bit predictor,
            which then also mispredicts step 4; the 2-bit counter only drops from <span className="mono">11</span> to <span className="mono">10</span> and still
            predicts TAKEN at step 4.
          </p>
        </section>

        <section id="metrics">
          <h2>7. Accuracy, penalty cycles and CPI</h2>
          <table className="data-table doc-table">
            <thead>
              <tr>
                <th scope="col">Quantity</th>
                <th scope="col">Formula</th>
                <th scope="col">What it tells you</th>
              </tr>
            </thead>
            <tbody>
              <tr><th scope="row">Accuracy</th><td className="mono">correct / branches × 100</td><td>How often the predictor guesses right. Depends only on the predictor and the branch sequence.</td></tr>
              <tr><th scope="row">Misprediction rate</th><td className="mono">M / branches × 100</td><td>100 % − accuracy.</td></tr>
              <tr><th scope="row">Penalty cycles</th><td className="mono">M × P</td><td>Cycles wasted on flushed wrong-path work.</td></tr>
              <tr><th scope="row">Estimated cycles</th><td className="mono">I + (L − 1) + M × P</td><td>Execution time of the whole program in this model.</td></tr>
              <tr><th scope="row">CPI</th><td className="mono">cycles / I</td><td>Average cycles per instruction over all I instructions, not just branches.</td></tr>
            </tbody>
          </table>
          <p>
            Accuracy is a property of the predictor on a workload; cycles and CPI also depend on the machine (L, P) and how many non-branch instructions there are. The
            same 90 % accuracy hurts much more on a deep pipeline with a large penalty, or in code where branches are frequent.
          </p>
        </section>

        <section id="limits">
          <h2>8. Limitations and real predictors</h2>
          <ul>
            <li><strong>Local history only.</strong> 1-bit and 2-bit predictors look at one branch's own recent outcomes, so they cannot learn alternating or other periodic patterns and ignore correlation between different branches.</li>
            <li><strong>Aliasing.</strong> Real tables are small and indexed by a few address bits, so different branches can share an entry. This simulator gives every address its own entry, so it shows no aliasing.</li>
            <li><strong>Direction only.</strong> Predicting TAKEN is useful only if the target address is also known early, which real processors handle with a branch target buffer (not modelled here).</li>
            <li><strong>Cold start.</strong> The first execution of each branch is predicted purely from the initial state.</li>
          </ul>
          <p>
            Modern processors therefore use more sophisticated schemes: correlating (global-history) predictors, two-level adaptive predictors, gshare, tournament
            predictors that choose between several, and TAGE- or perceptron-style predictors. They exist because deeper, wider pipelines make each misprediction more
            expensive. BranchLab does not model any particular commercial processor.
          </p>
        </section>
      </article>
    </div>
  );
}
